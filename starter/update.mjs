#!/usr/bin/env node
// Pull the latest starter changes into this project.
//
//   npm run starter:update
//
// Uses a real git merge, so your own changes are kept and only the starter's
// new changes come in. If both sides touched the same lines you'll get normal
// merge conflicts to resolve. package.json is merged key-by-key (so both sides
// adding dependencies is fine) and package-lock.json is regenerated automatically.

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rcPath = path.join(root, '.starterrc.json')

const git = (...a) =>
  execFileSync('git', a, { cwd: root, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
const tryGit = (...a) => {
  try {
    return git(...a)
  } catch {
    return null
  }
}
const run = (cmd, a) => execFileSync(cmd, a, { cwd: root, stdio: 'inherit' })

if (!existsSync(rcPath)) {
  fail(
    'No .starterrc.json found. This command is for projects created with "npm run new".\n' +
      '  (In the starter itself, use "npm run deps:update" to update dependencies.)',
  )
}
const { repo, branch = 'main' } = JSON.parse(readFileSync(rcPath, 'utf8'))

if (git('status', '--porcelain')) {
  fail('You have uncommitted changes. Commit or stash them first, then re-run.')
}

// Make sure the "starter" remote exists (it won't after a fresh clone of your own repo).
const currentUrl = tryGit('remote', 'get-url', 'starter')
if (currentUrl === null) git('remote', 'add', 'starter', repo)
else if (currentUrl !== repo) git('remote', 'set-url', 'starter', repo)

console.log(`→ Fetching starter from ${repo} (${branch})`)
run('git', ['fetch', '--no-tags', 'starter', branch])

const ref = `starter/${branch}`
const incoming = git('rev-list', '--count', `HEAD..${ref}`)
if (incoming === '0') {
  console.log('✔ Already up to date with the starter.')
  process.exit(0)
}

console.log(`\nIncoming starter changes (${incoming} commit${incoming === '1' ? '' : 's'}):`)
console.log(git('log', '--oneline', '--no-decorate', `HEAD..${ref}`) + '\n')

const before = git('rev-parse', 'HEAD')
// --allow-unrelated-histories lets this work for projects that weren't cloned from the starter.
const merged =
  tryGit('merge', '--no-ff', '--allow-unrelated-histories', '-m', 'Update from starter', ref) !==
  null

if (!merged) {
  let conflicts = git('diff', '--name-only', '--diff-filter=U').split('\n').filter(Boolean)

  if (conflicts.includes('package.json')) {
    const clashes = mergePackageJson()
    if (clashes) {
      console.log(
        '⚠ package.json: you and the starter changed the same keys. Kept YOUR values for:',
      )
      console.log(clashes.map((c) => `   - ${c}`).join('\n') + '\n')
    }
  }
  if (conflicts.includes('package-lock.json')) {
    // Lockfiles can't be hand-merged; it's regenerated by npm install below.
    git('checkout', '--ours', 'package-lock.json')
    git('add', 'package-lock.json')
  }

  conflicts = git('diff', '--name-only', '--diff-filter=U').split('\n').filter(Boolean)
  if (conflicts.length) {
    console.log(`
⚠ Merge conflicts in:
${conflicts.map((f) => `   - ${f}`).join('\n')}

Fix them (look for <<<<<<< markers), then run:
   npm install
   git add -A && git commit --no-edit

Or cancel the whole update with:  git merge --abort
`)
    process.exit(1)
  }

  console.log('→ Installing dependencies…')
  run('npm', ['install'])
  git('add', '-A')
  git('commit', '--no-edit')
} else {
  const changed = git('diff', '--name-only', before, 'HEAD').split('\n')
  if (changed.some((f) => f === 'package.json' || f === 'package-lock.json')) {
    console.log('→ Dependencies changed, installing…')
    run('npm', ['install'])
    if (git('status', '--porcelain')) {
      git('add', 'package-lock.json')
      git('commit', '-m', 'Update lockfile after starter update')
    }
  }
}

console.log('\n✔ Updated from starter. Run "npm run check" to make sure everything still passes.')

/**
 * 3-way merge of package.json by key: takes the starter's changes unless you changed the same
 * key too (then yours wins). Returns the list of clashing keys, or null if there were none.
 */
function mergePackageJson() {
  const read = (stage) => JSON.parse(git('show', `:${stage}:package.json`))
  const [base, ours, theirs] = [read(1), read(2), read(3)]
  const clashes = []
  const same = (a, b) => JSON.stringify(a) === JSON.stringify(b)
  const isObj = (v) => v && typeof v === 'object' && !Array.isArray(v)

  const merge = (b, o, t, keyPath) => {
    if (same(o, t) || same(b, t)) return o
    if (same(b, o)) return t
    if (isObj(o) && isObj(t)) {
      b = isObj(b) ? b : {}
      const out = {}
      for (const k of new Set([...Object.keys(o), ...Object.keys(t), ...Object.keys(b)])) {
        const v = merge(b[k], o[k], t[k], [...keyPath, k])
        if (v !== undefined) out[k] = v
      }
      // npm keeps dependency lists sorted
      return /dependencies$/i.test(keyPath.at(-1) ?? '')
        ? Object.fromEntries(Object.entries(out).sort(([a], [z]) => a.localeCompare(z)))
        : out
    }
    clashes.push(keyPath.join('.'))
    return o
  }

  const merged = merge(base, ours, theirs, [])
  writeFileSync(path.join(root, 'package.json'), JSON.stringify(merged, null, 2) + '\n')
  git('add', 'package.json')
  return clashes.length ? clashes : null
}

function fail(msg) {
  console.error(`✖ ${msg}`)
  process.exit(1)
}
